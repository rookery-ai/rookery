def icon(name: str, x: float, y: float, size: float, color: str,
         width: float = 1.9) -> str:
    """Draw a lucide icon with its top-left at (x, y), scaled to `size` px."""
    s = size / 24.0
    body = "".join(LUCIDE[name])
    return (
        f'<g transform="translate({r(x)} {r(y)}) scale({r(s, 4)})" '
        f'fill="none" stroke="{color}" color="{color}" stroke-width="{width / s:.3f}" '
        f'stroke-linecap="round" stroke-linejoin="round">{body}</g>'
    )


# --------------------------------------------------------------------------
# brand marks
# --------------------------------------------------------------------------

_VIEWBOX = re.compile(r'viewBox="([\d.\-\s]+)"')
_ROOT = re.compile(r"^\s*<svg\b([^>]*)>(.*)</svg>\s*$", re.S)
_ID = re.compile(r'\bid="([^"]+)"')


def _namespace_ids(body: str, prefix: str) -> str:
    """Rewrite every internal id and every reference to it.

    Vendored marks reuse trivial ids — dropbox.svg and jira.svg both define
    `a` and `b`. Inline two of those in one document and the second mark's
    url(#a) resolves to the FIRST mark's gradient, which renders as a plausible
    wrong colour rather than as an error. Prefixing per mark is what prevents it.
    """
    ids = set(_ID.findall(body))
    for i in sorted(ids, key=len, reverse=True):
        new = f"{prefix}-{i}"
        body = body.replace(f'id="{i}"', f'id="{new}"')
        body = body.replace(f"url(#{i})", f"url(#{new})")
        body = body.replace(f'href="#{i}"', f'href="#{new}"')
    return body


def logo(slug: str, cx: float, cy: float, size: float, ink: str,
         max_ar: float = 1.25) -> str:
    """Draw a vendored brand mark centred on (cx, cy), fitted into `size` px.

    `max_ar` rejects wordmarks. A mark is fitted by its LONGEST side, so a wide
    lockup like stripe.svg (512x214) lands at 40% of the intended height and
    reads as a smudge next to square marks — visible only once rendered, and
    easy to mistake for a bad logo rather than a bad fit. Chat pills pass a
    looser bound because the Discord mark is genuinely wide at 1.35.
    """
    src = (LOGO_DIR / f"{slug}.svg").read_text()
    m = _ROOT.match(src.strip())
    if not m:
        sys.exit(f"gen-readme-assets: {slug}.svg has no parseable <svg> root")
    attrs, body = m.group(1), m.group(2)

    vb = _VIEWBOX.search(attrs)
    if not vb:
        sys.exit(f"gen-readme-assets: {slug}.svg declares no viewBox")
    x0, y0, w, h = (float(v) for v in vb.group(1).split())

    ar = w / h
    if not (1 / max_ar) <= ar <= max_ar:
        sys.exit(
            f"gen-readme-assets: {slug}.svg is {w:g}x{h:g} (aspect {ar:.2f}), "
            f"outside the {1 / max_ar:.2f}-{max_ar:.2f} band — it is a wordmark, "
            "not a square mark, and would render far smaller than its neighbours. "
            "Pick a different provider."
        )

    if "<style" in body or "class=" in body:
        # vendor-brand-logos.sh inlines class styles and strips <style>; a mark
        # that still carries either would render at the SVG default fill (black)
        # here, since there is no stylesheet in an <img>-rendered document.
        sys.exit(f"gen-readme-assets: {slug}.svg still carries class/<style>")

    body = _namespace_ids(body, slug.replace("_", "-"))

    scale = size / max(w, h)
    tx = cx - (w * scale) / 2 - x0 * scale
    ty = cy - (h * scale) / 2 - y0 * scale

    # Carry the root's own paint attributes onto the wrapper: several marks set
    # fill/fill-rule there and would otherwise lose them with the root. `color`
    # is set because a currentColor mark (github.svg) resolves it against the
    # CSS color property, which defaults to black — invisible on the dark sheet.
    carried = " ".join(
        f'{k}="{v}"'
        for k, v in re.findall(r'\b(fill|fill-rule|clip-rule|stroke)="([^"]+)"', attrs)
    )
    return (
        f'<g transform="translate({r(tx)} {r(ty)}) scale({r(scale, 5)})" '
        f'color="{ink}" {carried}>{body}</g>'
    )


# --------------------------------------------------------------------------
# helpers
# --------------------------------------------------------------------------

def r(v: float, places: int = 2) -> str:
    """Trim float noise so the committed files diff readably."""
    s = f"{v:.{places}f}".rstrip("0").rstrip(".")
    return s or "0"


def esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def text(s: str, x: float, y: float, size: float, fill: str, *,
         weight: int = 400, anchor: str = "start", spacing: float | None = None,
         opacity: float | None = None) -> str:
    extra = ""
    if weight != 400:
        extra += f' font-weight="{weight}"'
    if anchor != "start":
        extra += f' text-anchor="{anchor}"'
    if spacing is not None:
        extra += f' letter-spacing="{spacing}"'
    if opacity is not None:
        extra += f' opacity="{opacity}"'
    return (
        f'<text x="{r(x)}" y="{r(y)}" font-size="{r(size)}" '
        f'fill="{fill}"{extra}>{esc(s)}</text>'
    )


def document(w: float, h: float, title: str, body: str) -> str:
    tid = re.sub(r"[^a-z]+", "-", title.lower()).strip("-")[:32]
    # xmlns:xlink is declared even though nothing here writes it: some vendored
    # marks (jira.svg) carry `xlink:href` on their gradients, and the prefix was
    # bound on the root <svg> that inlining discards. Without the declaration the
    # document is not well-formed XML and every browser renders a broken image.
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" '
        f'xmlns:xlink="http://www.w3.org/1999/xlink" '
        f'viewBox="0 0 {r(w)} {r(h)}" '
        f'width="{r(w)}" height="{r(h)}" role="img" aria-labelledby="{tid}">'
        f"<title id=\"{tid}\">{esc(title)}</title>"
        f'<g font-family="{FONT}">{body}</g>'
        "</svg>\n"
    )


