BUILDERS = {"hero-banner": hero, "features": features, "architecture": architecture}


def validate(path: Path, svg: str) -> None:
    """Refuse to write a file GitHub would render as a broken image.

    Both halves have already caught a real defect. A vendored mark carried
    `xlink:href` whose prefix was bound on the root element inlining discards,
    which is malformed XML — the browser shows the broken-image glyph, and
    nothing else in the toolchain would have said so.
    """
    import xml.etree.ElementTree as ET

    try:
        ET.fromstring(svg)
    except ET.ParseError as e:
        sys.exit(f"gen-readme-assets: {path.name} is not well-formed XML: {e}")

    # GitHub serves a README image as a bare <img>: no stylesheet, no script,
    # no fetch of a second file. Anything below would silently not apply.
    for bad, why in (
        ("<style", "a stylesheet does not apply inside an <img>"),
        ("class=", "class selectors have no stylesheet to match"),
        ("@import", "external resources are not fetched"),
        ("font-face", "webfonts are not loaded"),
        ("<script", "scripts do not execute"),
    ):
        if bad in svg:
            sys.exit(f"gen-readme-assets: {path.name} contains {bad!r} — {why}")

    ids = _ID.findall(svg)
    dupes = {i for i in ids if ids.count(i) > 1}
    if dupes:
        sys.exit(
            f"gen-readme-assets: {path.name} has duplicate ids {sorted(dupes)} — "
            "a later url(#id) would resolve to the earlier element"
        )


def render_all() -> dict[Path, str]:
    out: dict[Path, str] = {}
    for name, build in BUILDERS.items():
        for suffix, palette in (("", LIGHT), ("-dark", DARK)):
            path = OUT_DIR / f"{name}{suffix}.svg"
            svg = build(palette)
            validate(path, svg)
            out[path] = svg
    return out


def main(argv: list[str]) -> int:
    check = "--check" in argv
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    stale: list[str] = []
    for path, svg in render_all().items():
        rel = path.relative_to(ROOT)
        if check:
            if not path.exists() or path.read_text() != svg:
                stale.append(str(rel))
            continue
        path.write_text(svg)
        print(f"wrote {rel}  ({len(svg.encode()):,} bytes)")
    if check:
        if stale:
            print(
                "docs/assets is stale — these no longer match a fresh render:\n  "
                + "\n  ".join(stale)
                + "\n\nRun: python3 scripts/gen-readme-assets.py",
                file=sys.stderr,
            )
            return 1
        print(f"docs/assets: {len(BUILDERS) * 2} images match a fresh render")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
