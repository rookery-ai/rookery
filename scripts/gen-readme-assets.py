#!/usr/bin/env python3
"""Generate the three README images, in a light and a dark variant each.

    python3 scripts/gen-readme-assets.py

Writes six files into docs/assets/. Never hand-edit those — a re-run silently
overwrites them. Change this script instead.

Why a generator and not six checked-in files: each asset exists twice, once per
theme, and the two differ ONLY in the palette. Hand-maintaining that pair is the
same drift trap CLAUDE.md records for the provider count — the second copy stops
matching the first and nothing fails. Here the pair is one source and one loop.

Three constraints come from GitHub rendering a README image as a bare <img>,
in isolation, with no document around it:

  * No external anything. No <style>, no class=, no webfont, no href to another
    file. Everything is a presentation attribute on the element itself.
  * <text> renders in the VIEWER's fonts, so metrics vary by platform. Every
    string here is short and every box has slack; nothing is measured-to-fit.
  * `prefers-color-scheme` cannot reach inside the image, so the theme swap
    happens OUTSIDE it, via <picture> in the README. Hence two files.

Brand marks are read from web/ui/src/assets/logos/ (the vendored set, itself
generated by scripts/vendor-brand-logos.sh) rather than copied here, so a
re-vendor reaches these images too.
"""

from __future__ import annotations

